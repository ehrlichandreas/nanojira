/* ---- archive: only the moved subtree's paths change; body stays verbatim */

{
  const d = H.mkBacklog({
    label: 'archive-byte-id-archive',
    files: {
      'epics/EPIC-001.md': H.element({
        id: 'EPIC-001', type: 'epic', title: 'Auth', status: 'done',
        created: C, updated: C,
      }, '# Auth\n\n## Description\nGroundwork.\n\n  Indented on purpose.\n'),
      'tasks/TSK-001.md': H.element({
        id: 'TSK-001', type: 'task', parent: 'EPIC-001', title: 'Archived task',
        status: 'done', created: C, updated: C,
      }, '# Archived task\n\n## Description\nD\n\n## Acceptance Criteria\n- [ ] x\n\n' +
        '## Notes\n- ' + C + ' coder-agent: keep me\n'),
      'epics/EPIC-002.md': H.element({
        id: 'EPIC-002', type: 'epic', title: 'Unrelated', status: 'todo',
        created: C, updated: C,
      }, '# Unrelated\n\n## Description\nD\n'),
      'tasks/TSK-002.md': H.element({
        id: 'TSK-002', type: 'task', parent: 'EPIC-002', title: 'Depends on the archived task',
        status: 'todo', depends_on: '[TSK-001]', created: C, updated: C,
      }, H.completeBody('Depends on the archived task')),
    },
    tombstones: ['EPIC-001', 'TSK-001', 'EPIC-002', 'TSK-002'],
  });

  const beforeEpicBody = bodyOf(fs.readFileSync(path.join(d, 'backlog', 'epics/EPIC-001.md'), 'utf8'));
  const beforeTaskBody = bodyOf(fs.readFileSync(path.join(d, 'backlog', 'tasks/TSK-001.md'), 'utf8'));

  const before = checksumAll(d);
  const r = H.runNj(['archive', '--id=EPIC-001'], { cwd: d, env: { NJ_NOW: LATER } });
  T.exit('archive --id=EPIC-001', r, 0);
  const after = checksumAll(d);

  assertOnlyTheTargetChanged('archive', before, after,
    ['epics/EPIC-001.md', 'tasks/TSK-001.md'],
    ['archive/EPIC-001.md', 'archive/TSK-001.md']);

  const afterEpicBody = bodyOf(H.readOrNull(path.join(d, 'backlog', 'archive/EPIC-001.md')));
  const afterTaskBody = bodyOf(H.readOrNull(path.join(d, 'backlog', 'archive/TSK-001.md')));
  T.eq('archiving the epic changes only the frontmatter, body is verbatim',
    afterEpicBody, beforeEpicBody);
  T.eq('archiving the task changes only the frontmatter, body (incl. Notes) is verbatim',
    afterTaskBody, beforeTaskBody);

  const list = H.runJson(['list'], { cwd: d });
  const t2 = ((list.json && list.json.entries) || []).find(e => e.id === 'TSK-002');
  T.check('the dependent surfaces active_refs_archived after the archive, file unchanged',
    !!t2 && (t2._problems || []).includes('active_refs_archived'), JSON.stringify(t2 && t2._problems));
}

T.finish();
