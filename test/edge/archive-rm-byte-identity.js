'use strict';
/* Edge — byte-identity of `rm`, `rm --cascade` and `archive` (Not-covered #6).
 *
 * The refactor this oracle guards rests on one claim: behaviour stays
 * byte-identical. For `rm`/`archive` that claim had never been tested — only
 * read by eye in the source. This file proves it mechanically: every file in
 * the backlog OTHER than the operation's own target(s) is checksummed before
 * and after, and must match exactly. No file is trusted by name; the sweep
 * walks the whole `backlog/` tree, so a stray write anywhere — a sibling, an
 * unrelated subtree, a dependent element, a tombstone, `.nanojira/config.json` — is
 * caught, not just the handful of paths a narrower test happens to name.
 *
 * § 6/§ 7: problem codes (`depends_on:dangling`, `active_refs_archived`, …)
 * are "derived, never stored" — a dependent element's own file must never be
 * rewritten just because something it points at was removed or archived.
 * That invariant is exactly what the sweep proves for the "everything else"
 * set: if it were violated, the dependent's checksum would differ and the
 * sweep would catch it directly, with no need to single it out by name.
 *
 * § 11: archiving does not touch the body, only the frontmatter (`archived`
 * added, `updated` refreshed) — verified here as a general rule (the body
 * bytes below the closing `---` are compared verbatim), not merely against
 * one canned golden fixture.
 */
const fs = require('fs');
const path = require('path');
const H = require('../lib/harness.js');
const T = H.T;

const C = H.FIXED_NOW;
const LATER = H.LATER_NOW;

/** Every file under backlog/, relative path -> sha256, walked deterministically. */
/* STATUS.md (spec v3 § 4) is regenerated by every successful write and is
 * left out of the compared set: this suite is about element bytes
 * (DECISIONS 100). AC-23 pins the overview itself. */
function checksumAll(d) {
  const root = path.join(d, 'backlog');
  const map = {};
  (function walk(dir, rel) {
    for (const name of H.lsOrEmpty(dir)) {
      const abs = path.join(dir, name);
      const r = rel ? rel + '/' + name : name;
      if (r === 'STATUS.md') continue;
      let st = null;
      try { st = fs.statSync(abs); } catch (e) { /* dangling link: hashed as unreadable */ }
      if (st && st.isDirectory()) walk(abs, r);
      else map[r] = (() => { try { return H.sha256(fs.readFileSync(abs)); } catch (e) { return '<unreadable>'; } })();
    }
  })(root, '');
  return map;
}

/**
 * Assert that `after` differs from `before` in EXACTLY the expected way:
 * `removed` paths existed before and are gone after, `added` paths did not
 * exist before and exist after, and every other path that was present before
 * is still present with an unchanged checksum. Also catches unexpected extra
 * writes (a stray .nj-tmp-*, an accidentally touched sibling) by requiring
 * no file to appear that isn't one of the declared additions.
 */
function assertOnlyTheTargetChanged(label, before, after, removed, added) {
  const addedSet = new Set(added);

  for (const rel of removed) {
    T.check(label + ': ' + rel + ' existed before', rel in before, 'missing from before-sweep');
    T.check(label + ': ' + rel + ' is gone after', !(rel in after), 'still present after');
  }
  for (const rel of added) {
    T.check(label + ': ' + rel + ' did not exist before', !(rel in before), 'unexpectedly present before');
    T.check(label + ': ' + rel + ' exists after', rel in after, 'missing from after-sweep');
  }

  const untouched = Object.keys(before).filter(rel => !removed.includes(rel));
  for (const rel of untouched) {
    T.check(label + ': ' + rel + ' is byte-identical', after[rel] === before[rel],
      'checksum changed: ' + before[rel] + ' -> ' + after[rel]);
  }

  const unexpectedNew = Object.keys(after).filter(rel => !(rel in before) && !addedSet.has(rel));
  T.check(label + ': no unexpected file appeared', unexpectedNew.length === 0,
    JSON.stringify(unexpectedNew));
}

/** The body (everything after the closing '---' of the frontmatter block). */
/* Null-safe: a partial nj may not have produced the file at all, and that
 * must surface as a failed comparison, never as a TypeError (README,
 * "contexts the suite must survive"). */
function bodyOf(text) {
  if (text === null) return '<file missing>';
  const lines = text.split('\n');
  if (lines[0] !== '---') return text;
  const end = lines.indexOf('---', 1);
  if (end === -1) return text;
  return lines.slice(end + 1).join('\n');
}

/* ---- rm (single, non-cascade): everything else stays byte-identical ---- */

{
  const d = H.mkBacklog({
    label: 'archive-byte-id-rm',
    files: {
      'epics/EPIC-001.md': H.element({
        id: 'EPIC-001', type: 'epic', title: 'Auth', status: 'todo',
        created: C, updated: C,
      }, '# Auth\n\n## Description\nD\n'),
      'tasks/TSK-001.md': H.element({
        id: 'TSK-001', type: 'task', parent: 'EPIC-001', title: 'Removed leaf',
        status: 'todo', created: C, updated: C,
      }, H.completeBody('Removed leaf')),
      'epics/EPIC-002.md': H.element({
        id: 'EPIC-002', type: 'epic', title: 'Unrelated', status: 'todo',
        created: C, updated: C,
      }, '# Unrelated\n\n## Description\nD\n'),
      'tasks/TSK-002.md': H.element({
        id: 'TSK-002', type: 'task', parent: 'EPIC-002', title: 'Untouched sibling area',
        status: 'todo', created: C, updated: C,
      }, H.completeBody('Untouched sibling area')),
      'tasks/TSK-003.md': H.element({
        id: 'TSK-003', type: 'task', parent: 'EPIC-002', title: 'Depends on the removed one',
        status: 'todo', depends_on: '[TSK-001]', created: C, updated: C,
      }, H.completeBody('Depends on the removed one')),
    },
    tombstones: ['EPIC-001', 'TSK-001', 'EPIC-002', 'TSK-002', 'TSK-003'],
  });

  const before = checksumAll(d);
  const r = H.runNj(['rm', '--id=TSK-001'], { cwd: d, env: { NJ_NOW: LATER } });
  T.exit('rm --id=TSK-001', r, 0);
  const after = checksumAll(d);

  assertOnlyTheTargetChanged('rm', before, after, ['tasks/TSK-001.md'], []);

  /* the dependent's file is untouched (proven above); its DERIVED read output
   * changes — that split is the point of "derived, never stored". */
  const list = H.runJson(['list'], { cwd: d });
  const t3 = ((list.json && list.json.entries) || []).find(e => e.id === 'TSK-003');
  T.check('the dependent surfaces depends_on:dangling on read, despite an unchanged file',
    !!t3 && (t3._problems || []).includes('depends_on:dangling'), JSON.stringify(t3 && t3._problems));
}

